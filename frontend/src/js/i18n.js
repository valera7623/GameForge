export function getLang() {
  return localStorage.getItem("gf_lang") === "ru" ? "ru" : "en";
}

export function setLang(lang) {
  localStorage.setItem("gf_lang", lang === "ru" ? "ru" : "en");
}

/** Translate key; optional {name} placeholders via params. */
export function t(key, params) {
  const lang = getLang();
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Apply data-i18n / data-i18n-attr / data-i18n-html on a subtree. */
export function applyDomI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const attr = el.getAttribute("data-i18n-attr");
    const val = t(key);
    if (attr) el.setAttribute(attr, val);
    else if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
    else el.textContent = val;
  });
  document.documentElement.lang = getLang();
  const titled = document.querySelector("title[data-i18n]");
  if (titled) document.title = t(titled.getAttribute("data-i18n"));
  else {
    const titleKey = document.body?.dataset?.i18nTitle;
    if (titleKey) document.title = t(titleKey);
  }
}
